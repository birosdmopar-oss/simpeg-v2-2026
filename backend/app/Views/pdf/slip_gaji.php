<?php
/**
 * PDF slip gaji (PRD 5A §7.3.6) — port tata letak legacy `0cf7e67` `views/hr/employee/sl_gaji/print/cetak.php` [K]:
 * kotak dokumen berisi kop, judul "SLIP GAJI", identitas + QR, rincian A. GPP (dua kolom penghasilan | potongan) →
 * B. TK → C. Uang Makan → Ringkasan Penghasilan.
 *
 * [CATAT] Tata letak slip dirapikan (masukan Horii 25-11-2026 dari app demo; CR-192) — nilai, label rincian, urutan
 * bagian, kalimat, dan isi QR TIDAK berubah; yang berubah hanya letak dan ukuran:
 * judul "SLIP GAJI" tebal 11,5pt; identitas di kiri (72%) dan QR ±29 mm di kanan dengan label "Generated by SIMPEG v2"
 * (sebelumnya "Generated by SIMPEG" di dalam kotak), tanggal cetak, dan "Dibuka" di bawahnya; kalimat "adalah benar
 * pegawai …", Bulan/Tahun, dan "Menurut Rincian di bawah ini :" selebar penuh di bawah identitas + QR (sebelumnya di
 * kolom kiri 68% sehingga terlipat); jarak antar-blok kepala seragam; kolom "Rp." dan nominal baris selebar penuh
 * sejajar dengan sisi potongan; potongan bernilai nol ditulis "0" seperti penghasilan nol (bukan "- 0").
 *
 * [CATAT] Kop seragam (keputusan Horii 24-11-2026, acuan gambar; CR-191): kop lewat `KopResmi` (logo kiri | nama
 * kementerian, unit, alamat | logo kanan, garis) — menggantikan tata letak kop legacy slip. Semua teks di-escape
 * (`esc`); teks kop `web_config` (G-09) dijadikan teks polos oleh `KopResmi` (hanya ganti baris dipertahankan; tautan
 * dan tag lain dibuang).
 *
 * @var App\Libraries\Presensi\Slip\DataPdfSlip                                $d
 * @var string|null                                                            $qr
 * @var array{jumlah_penghasilan_gpp: int, jumlah_potongan_gpp: int, bersih_gpp: int, bersih_tk: int, bersih_2: int, total_penghasilan: int} $ringkasan
 * @var array<string, string>                                                  $labelGpp
 * @var array<string, string>                                                  $labelTk
 * @var string                                                                 $labelUm
 * @var string                                                                 $tglCetak
 * @var string|null                                                            $dibuka
 */

use App\Libraries\Pdf\KopResmi;
use App\Libraries\Presensi\SlipGaji\FormatSlip;
use App\Libraries\Presensi\SlipGaji\NominalGaji;

$rp  = static fn (int $sen): string => NominalGaji::formatAngka($sen);
$sen = static fn (string $f): int => $d->sen[$f] ?? 0;

// Kelompok rincian [K print/cetak.php @771f8b4 :262-277; TK @0cf7e67 :274-277].
$gppGroups = [
    'Penghasilan' => [
        'Gaji Pokok'         => ['gjpokok'],
        'Tunjangan Keluarga' => ['tjistri', 'tjanak'],
        'Tunjangan Jabatan'  => ['tjstruk', 'tjfungs'],
        'Tunjangan Lainnya'  => ['tjupns', 'tjdaerah', 'tjberas', 'tjpencil', 'tjkompen', 'tjlain', 'tjpph', 'pembul'],
    ],
    'Potongan' => [
        'Iuran & Pajak'    => ['potpfkbul', 'potpfk2', 'potpfk10', 'potpph'],
        'Potongan Lainnya' => ['potswrum', 'potkelbtj', 'pottabrum', 'potlain'],
    ],
];
// TK hanya Penghasilan Kotor & Potongan; baris "Pajak" dan "Tunjangan Pajak" dihapus [K print/cetak.php @0cf7e67 :274-277]
// (CR-067). Kolom `pajak`/`tunj_pajak` tetap disimpan & diimpor; hanya tidak ditampilkan.
$tkGroups = ['Penghasilan' => ['kotor'], 'Potongan' => ['potongan']];

// Lebar kolom (persen). Setengah halaman (penghasilan | potongan): label | Rp. | nominal. Baris selebar penuh memakai
// lebar yang sama dengan sisi KANAN (53% + 47% × label, dst.) supaya kolom "Rp." dan nominal potongan, jumlah, bersih,
// dan uang makan berada pada satu garis tegak (CR-192).
$lebarSisi   = 47;
$lebarCelah  = 100 - 2 * $lebarSisi;
$kolSetengah = [62, 9, 29];
$kolPenuh    = [
    round($lebarSisi + $lebarCelah + $lebarSisi * $kolSetengah[0] / 100, 2),
    round($lebarSisi * $kolSetengah[1] / 100, 2),
    round($lebarSisi * $kolSetengah[2] / 100, 2),
];
// Potongan ditampilkan bertanda "-" [K]; potongan bernilai nol ditulis "0" seperti penghasilan nol (bukan "- 0").
$nominal = static fn (int $nilai, bool $neg): string => ($neg && $nilai !== 0 ? '-&nbsp;' : '') . $rp($nilai);

$baris = static fn (string $label, int $nilai, int $indent = 0, bool $neg = false): string => '<tr>'
    . '<td width="' . $kolPenuh[0] . '%" align="left" style="padding-left: ' . $indent . 'px;">' . esc($label) . '</td>'
    . '<td width="' . $kolPenuh[1] . '%" align="right">Rp.</td>'
    . '<td width="' . $kolPenuh[2] . '%" align="right">' . $nominal($nilai, $neg) . '</td></tr>';
$tint = static fn (string $label, int $nilai, string $bg, float $pt, bool $neg = false): string => '<tr bgcolor="' . $bg . '">'
    . '<td width="' . $kolPenuh[0] . '%" align="left" style="font-size: ' . $pt . 'pt; padding-left: 4px;"><b>' . esc($label) . '</b></td>'
    . '<td width="' . $kolPenuh[1] . '%" align="right" style="font-size: ' . $pt . 'pt;"><b>Rp.</b></td>'
    . '<td width="' . $kolPenuh[2] . '%" align="right" style="font-size: ' . $pt . 'pt;"><b>' . $nominal($nilai, $neg) . '</b></td></tr>';
$sp = static fn (int $px): string => '<tr><td colspan="3" style="font-size: ' . $px . 'px; line-height: ' . $px . 'px;">&nbsp;</td></tr>';
// Jarak bagian 8/8/4 px (sebelumnya 10/10/5): kepala slip kini lebih tinggi beberapa mm, dan slip wajib tetap satu halaman.
$section = static fn (string $judul): string => $sp(8)
    . '<tr><td colspan="3" style="border-top: 0.75px solid #777777; font-size: 1px; line-height: 1px;">&nbsp;</td></tr>'
    . $sp(8) . '<tr><td colspan="3" align="left" style="font-size: 8.5pt; font-weight: bold;">' . esc($judul) . '</td></tr>' . $sp(4);
$setengah = static fn (string $label, int $nilai, int $indent, bool $neg): string => '<tr>'
    . '<td width="' . $kolSetengah[0] . '%" align="left" style="padding-left: ' . $indent . 'px;">' . esc($label) . '</td>'
    . '<td width="' . $kolSetengah[1] . '%" align="right">Rp.</td><td width="' . $kolSetengah[2] . '%" align="right">' . $nominal($nilai, $neg) . '</td></tr>';
$grup         = static fn (string $judul): string => '<tr><td colspan="3" align="left" style="font-size: 7pt; font-weight: bold; color: #666666;">' . esc(mb_strtoupper($judul)) . '</td></tr>';
$sub          = static fn (string $judul): string => '<tr><td colspan="3" align="left" style="padding-left: 6px; font-size: 7.5pt;"><b>' . esc($judul) . '</b></td></tr>';
$tintSetengah = static fn (string $label, int $nilai, bool $neg = false): string => '<table width="100%" cellpadding="0" cellspacing="0" border="0"><tr bgcolor="#f3f4f6">'
    . '<td width="' . $kolSetengah[0] . '%" align="left" style="font-size: 7.5pt; padding-left: 4px;"><b>' . esc($label) . '</b></td>'
    . '<td width="' . $kolSetengah[1] . '%" align="right" style="font-size: 7.5pt;"><b>Rp.</b></td>'
    . '<td width="' . $kolSetengah[2] . '%" align="right" style="font-size: 7.5pt;"><b>' . $nominal($nilai, $neg) . '</b></td></tr></table>';
$duaKolom = static fn (string $kiri, string $kanan): string => '<tr><td colspan="3"><table width="100%" cellpadding="0" cellspacing="0" border="0"><tr>'
    . '<td width="' . $lebarSisi . '%" valign="top">' . $kiri . '</td><td width="' . $lebarCelah . '%"></td><td width="' . $lebarSisi . '%" valign="top">' . $kanan . '</td></tr></table></td></tr>';
// Jarak tegak seragam antar-blok kepala slip (kop → judul → identitas/QR → kalimat pengantar).
$jarak = '<table width="100%" cellpadding="0" cellspacing="0" border="0"><tr><td style="font-size: 1px; line-height: 8px;">&nbsp;</td></tr></table>';

$sisiGpp = [];
foreach ($gppGroups as $nama => $subGrup) {
    $pot  = $nama === 'Potongan';
    $html = $grup($nama);
    foreach ($subGrup as $judul => $field) {
        $datar = count($field) === 1 && $judul === $labelGpp[$field[0]];
        if (! $datar) {
            $html .= $sub($judul);
        }
        foreach ($field as $f) {
            $html .= $setengah($labelGpp[$f], $sen($f), $datar ? 6 : 16, $pot);
        }
    }
    $sisiGpp[$nama] = '<table width="100%" cellpadding="0" cellspacing="0" border="0">' . $html . '</table>';
}

$sisiTk = [];
foreach ($tkGroups as $nama => $field) {
    $pot  = $nama === 'Potongan';
    $html = $grup($nama);
    foreach ($field as $f) {
        $html .= $setengah($labelTk[$f], $sen($f), 6, $pot);
    }
    $sisiTk[$nama] = '<table width="100%" cellpadding="0" cellspacing="0" border="0">' . $html . '</table>';
}

$labelGppBersih = 'Gaji Pokok dan Pendapatan (GPP) Bersih';
$labelTkBersih  = 'Tunjangan Kinerja (TK) Bersih';
$identitas      = [
    'Nama'    => $d->identitas['nama'], 'NIP' => $d->identitas['nip'], 'Pangkat / Gol' => $d->identitas['pangkat'],
    'Jabatan' => $d->identitas['jabatan'], 'Satuan Organisasi' => $d->identitas['unit'], 'Satuan Kerja' => $d->identitas['satker'],
];
?>
<style>
    body { font-family: helvetica; font-size: 8.5pt; color: #000000; }
    .tbl-ident td { font-size: 8.5pt; line-height: 1.6; }
    .tbl-identitas td { line-height: 1.7; }
    .tbl-section td { font-size: 7.5pt; line-height: 1.4; }
</style>
<table width="100%" cellpadding="16" cellspacing="0" border="0" style="border: 1px solid #000000;">
<tr><td>
    <?= KopResmi::html($d->kop['nama_kementerian'], $d->kop['nama_unit'], $d->kop['alamat'], $d->logoKiri, $d->logoKanan) ?>

    <?= $jarak ?>
    <table width="100%" cellpadding="0" cellspacing="0" border="0">
        <tr><td align="center" style="font-size: 11.5pt; font-weight: bold;">SLIP GAJI</td></tr>
    </table>
    <?= $jarak ?>

    <table width="100%" cellpadding="0" cellspacing="0" border="0">
        <tr>
            <td width="72%" valign="top"><table class="tbl-ident tbl-identitas" width="100%" cellpadding="0" cellspacing="0" border="0">
<?php foreach ($identitas as $label => $nilai): ?>
                    <tr><td width="27%" align="left"><?= esc($label) ?></td><td width="3%" align="center">:</td><td width="70%" align="left"><?= esc($nilai) ?></td></tr>
<?php endforeach ?>
                </table>
            </td>
            <td width="28%" valign="top" align="center">
<?php if ($qr !== null): ?>
                <table width="100%" cellpadding="0" cellspacing="0" border="0"><tr><td align="center" style="font-size: 1px; line-height: 1px;"><?= $qr ?></td></tr></table>
<?php endif ?>
                <table width="100%" cellpadding="0" cellspacing="0" border="0">
                    <tr><td style="font-size: 1px; line-height: 3px;">&nbsp;</td></tr>
                    <tr><td align="center" style="font-size: 6.5pt; line-height: 1.6; color: #555555;">Generated by SIMPEG v2</td></tr>
                    <tr><td align="center" style="font-size: 8pt; line-height: 1.4;">Jakarta, <?= esc($tglCetak) ?></td></tr>
<?php if ($dibuka !== null): ?>
                    <tr><td align="center" style="font-size: 7pt; line-height: 1.4; color: #555555;">Dibuka: <?= esc($dibuka) ?></td></tr>
<?php endif ?>
                </table>
            </td>
        </tr>
    </table>
    <?= $jarak ?>

    <table width="100%" cellpadding="0" cellspacing="0" border="0">
        <tr><td align="left" style="font-size: 8.5pt; line-height: 1.5;">adalah benar pegawai <?= esc($d->namaInstansi) ?>, mempunyai penghasilan bersih untuk bulan :</td></tr>
    </table>
    <table class="tbl-ident" width="100%" cellpadding="0" cellspacing="0" border="0">
        <tr><td width="19.44%" align="left">Bulan</td><td width="2.16%" align="center">:</td><td width="78.4%" align="left"><b><?= esc(explode(' ', $d->periode->label())[0]) ?></b></td></tr>
        <tr><td align="left">Tahun</td><td align="center">:</td><td align="left"><b><?= esc((string) $d->periode->tahun) ?></b></td></tr>
    </table>
    <table width="100%" cellpadding="0" cellspacing="0" border="0">
        <tr><td align="left" style="font-size: 8.5pt; line-height: 1.5;">Menurut Rincian di bawah ini :</td></tr>
    </table>

    <table class="tbl-section" width="100%" cellpadding="0" cellspacing="0" border="0">
        <?= $section('A. GAJI POKOK & PENDAPATAN (GPP)') ?>
        <?= $duaKolom($sisiGpp['Penghasilan'], $sisiGpp['Potongan']) ?>
        <?= $sp(3) ?>
        <?= $duaKolom($tintSetengah('Jumlah Penghasilan', $ringkasan['jumlah_penghasilan_gpp']), $tintSetengah('Jumlah Potongan', $ringkasan['jumlah_potongan_gpp'], true)) ?>
        <?= $sp(3) ?>
        <?= $tint($labelGppBersih, $ringkasan['bersih_gpp'], '#e4e9f0', 8) ?>

        <?= $section('B. TUNJANGAN KINERJA (TK)') ?>
        <?= $duaKolom($sisiTk['Penghasilan'], $sisiTk['Potongan']) ?>
        <?= $sp(3) ?>
        <?= $duaKolom($tintSetengah('Jumlah Penghasilan', $sen('kotor')), $tintSetengah('Jumlah Potongan', $sen('potongan'), true)) ?>
        <?= $sp(3) ?>
        <?= $tint($labelTkBersih, $ringkasan['bersih_tk'], '#e4e9f0', 8) ?>

        <?= $section('C. UANG MAKAN') ?>
        <?= $baris($labelUm, $sen('uang_makan'), 6) ?>

        <?= $section('RINGKASAN PENGHASILAN') ?>
        <tr><td colspan="3"><table width="100%" cellpadding="8" cellspacing="0" border="0" style="border: 1.2px solid #2c3e50;"><tr><td>
            <table class="tbl-section" width="100%" cellpadding="0" cellspacing="0" border="0">
                <?= $baris($labelGppBersih, $ringkasan['bersih_gpp']) ?>
                <?= $baris($labelTkBersih, $ringkasan['bersih_tk']) ?>
                <?= $baris('Uang Makan', $sen('uang_makan')) ?>
                <?= $sp(3) ?>
                <?= $tint(FormatSlip::labelTotal($d->periode), $ringkasan['total_penghasilan'], '#d5dbe3', 9) ?>
            </table>
        </td></tr></table></td></tr>
    </table>
</td></tr>
</table>
